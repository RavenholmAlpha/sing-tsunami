func TestServeHTTP2RejectsIncompleteConfig(t *testing.T) {
	serverConn, clientConn := net.Pipe()
	defer clientConn.Close()
	cfg := testFrontingConfig()
	cfg.Secret = ""
	err := ServeHTTP2(context.Background(), serverConn, cfg, echoTunnel, nil)
	if err == nil || !strings.Contains(err.Error(), "secret") {
		t.Fatalf("ServeHTTP2 with no secret = %v, want a secret error", err)
	}

	otherServer, otherClient := net.Pipe()
	defer otherClient.Close()
	if err := ServeHTTP2(context.Background(), otherServer, testFrontingConfig(), nil, nil); err == nil {
		t.Fatal("ServeHTTP2 accepted a nil tunnel handler")
	}

	if err := ServeHTTP2(context.Background(), nil, testFrontingConfig(), echoTunnel, nil); err == nil {
		t.Fatal("ServeHTTP2 accepted a nil connection")
	}
}

func TestH2ContextCancellationStopsServer(t *testing.T) {
	serverConn, clientConn := net.Pipe()
	ctx, cancel := context.WithCancel(context.Background())
	serveErr := make(chan error, 1)
	go func() { serveErr <- ServeHTTP2(ctx, serverConn, testFrontingConfig(), echoTunnel, nil) }()

	time.Sleep(20 * time.Millisecond)
	cancel()
	waitServe(t, serveErr, "ServeHTTP2 after cancel")
	_ = clientConn.Close()
}

