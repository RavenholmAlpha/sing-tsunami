// echoTunnel copies the tunnel byte stream back to the peer until it ends.
func echoTunnel(conn net.Conn) error {
	defer conn.Close()
	_, err := io.Copy(conn, conn)
	return err
}

// tunnelEchoResult is one echo round trip's outcome.
type tunnelEchoResult struct {
	data []byte
	err  error
}

// assertTunnelEcho writes payload into the tunnel and requires the echo back.
func assertTunnelEcho(t *testing.T, conn net.Conn, payload []byte) {
	t.Helper()
	resultCh := make(chan tunnelEchoResult, 1)
	go func() {
		if _, err := conn.Write(payload); err != nil {
			resultCh <- tunnelEchoResult{err: err}
			return
		}
		echoed := make([]byte, len(payload))
		_, err := io.ReadFull(conn, echoed)
		resultCh <- tunnelEchoResult{data: echoed, err: err}
	}()
	select {
	case result := <-resultCh:
		if result.err != nil {
			t.Fatalf("tunnel round trip: %v", result.err)
		}
		if !bytes.Equal(result.data, payload) {
			t.Fatalf("echo = %q, want %q", result.data, payload)
		}
	case <-time.After(20 * time.Second):
		t.Fatal("timed out waiting for the tunnel echo")
	}
}

// waitServe waits for a ServeHTTP1/ServeHTTP2 goroutine to return.
func waitServe(t *testing.T, serveErr <-chan error, label string) {
	t.Helper()
	select {
	case err := <-serveErr:
		if err != nil {
			t.Fatalf("%s: %v", label, err)
		}
	case <-time.After(20 * time.Second):
		t.Fatalf("timed out waiting for %s to return", label)
	}
}

// singleUseDialer returns an http2.Transport dial function that hands the
// already-handshaked connection to the transport exactly once.
func singleUseDialer(conn net.Conn) func(context.Context, string, string, *tls.Config) (net.Conn, error) {
	var dialed atomic.Bool
	return func(ctx context.Context, network, addr string, _ *tls.Config) (net.Conn, error) {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		if dialed.Swap(true) {
			return nil, errors.New("test: single-use connection dialed twice")
		}
		return conn, nil
	}
}

// runH2Request starts ServeHTTP2 on one end of a net.Pipe, issues req over the
// other end with a raw HTTP/2 client, and returns the response with its body.
func runH2Request(t *testing.T, cfg Config, method, path string, mutate func(*http.Request)) (*http.Response, []byte) {
	t.Helper()
	serverConn, clientConn := net.Pipe()
	serveErr := make(chan error, 1)
	go func() { serveErr <- ServeHTTP2(context.Background(), serverConn, cfg, echoTunnel, nil) }()

	transport := &http2.Transport{DialTLSContext: singleUseDialer(clientConn)}
	defer func() {
		transport.CloseIdleConnections()
		_ = clientConn.Close()
		waitServe(t, serveErr, "ServeHTTP2")
	}()

	req, err := http.NewRequest(method, "https://"+cfg.Host+path, nil)
	if err != nil {
		t.Fatalf("new request: %v", err)
	}
	req.Host = cfg.Host
	if mutate != nil {
		mutate(req)
	}
	resp, err := transport.RoundTrip(req)
	if err != nil {
		t.Fatalf("h2 %s %s: %v", method, path, err)
	}
	body, err := io.ReadAll(resp.Body)
	resp.Body.Close()
	if err != nil {
		t.Fatalf("read h2 response body: %v", err)
	}
	return resp, body
}

// assertBuiltinDecoy requires an ordinary HTML response generated by the
// built-in decoy site handler.
func assertBuiltinDecoy(t *testing.T, resp *http.Response, body []byte) {
	t.Helper()
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("status = %d, want 200", resp.StatusCode)
	}
	if got := resp.Header.Get("Content-Type"); got != "text/html; charset=utf-8" {
		t.Fatalf("Content-Type = %q, want the builtin page", got)
	}
	if got := resp.Header.Get("Server"); got != DefaultServerHeader {
		t.Fatalf("Server = %q, want %q", got, DefaultServerHeader)
	}
	page := string(body)
	if !strings.Contains(page, "<title>Welcome</title>") || !strings.Contains(page, "<h1>Welcome</h1>") {
		t.Fatalf("decoy page = %q", page)
	}
}

// assertDecoyNotFound requires the ordinary 404 the built-in decoy site
// answers for non-GET requests and unknown paths. It also proves the response
// did not come from the tunnel path.
func assertDecoyNotFound(t *testing.T, resp *http.Response, body []byte) {
	t.Helper()
	if resp.StatusCode != http.StatusNotFound {
		t.Fatalf("status = %d, want the decoy 404", resp.StatusCode)
	}
	if got := resp.Header.Get("Content-Type"); got != "text/plain; charset=utf-8" {
		t.Fatalf("Content-Type = %q, want the decoy's plain-text 404", got)
	}
	if got := resp.Header.Get("Server"); got != DefaultServerHeader {
		t.Fatalf("Server = %q, want %q", got, DefaultServerHeader)
	}
	if got := resp.Header.Get("Cache-Control"); got == "no-store" {
		t.Fatal("decoy response carries tunnel headers")
	}
	if !strings.Contains(string(body), "404 page not found") {
		t.Fatalf("body = %q", body)
	}
}

func TestH2LoopbackTunnel(t *testing.T) {
	serverConn, clientConn := net.Pipe()
	cfg := testFrontingConfig()
	serveErr := make(chan error, 1)
	go func() { serveErr <- ServeHTTP2(context.Background(), serverConn, cfg, echoTunnel, nil) }()

	tunnel, err := NewClientConn(clientConn, cfg)
	if err != nil {
		t.Fatalf("NewClientConn: %v", err)
	}
	assertTunnelEcho(t, tunnel, []byte("hello tsunami fronting"))

	// A payload crossing several DATA frames must survive the round trip.
	large := bytes.Repeat([]byte("abcdefgh"), 8<<10)
	assertTunnelEcho(t, tunnel, large)

	_ = tunnel.Close()
	_ = clientConn.Close()
	waitServe(t, serveErr, "ServeHTTP2")
}

func TestH2AuthenticatedResponseHeaders(t *testing.T) {
	serverConn, clientConn := net.Pipe()
	cfg := testFrontingConfig()
	serveErr := make(chan error, 1)
	go func() { serveErr <- ServeHTTP2(context.Background(), serverConn, cfg, echoTunnel, nil) }()

	transport := &http2.Transport{DialTLSContext: singleUseDialer(clientConn)}
	req, err := http.NewRequest(http.MethodPost, "https://"+cfg.Host+cfg.Path, nil)
	if err != nil {
		t.Fatalf("new request: %v", err)
	}
	req.Host = cfg.Host
	req.Header.Set("Content-Type", "application/octet-stream")
	req.Header.Set("Cache-Control", "no-store")
	SignRequest(req, KeyFromSecret(cfg.Secret), time.Now())

	resp, err := transport.RoundTrip(req)
	if err != nil {
		t.Fatalf("POST %s: %v", cfg.Path, err)
	}
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("status = %d, want 200", resp.StatusCode)
	}
	if resp.ProtoMajor < 2 {
		t.Fatalf("proto = %s, want HTTP/2", resp.Proto)
	}
	if got := resp.Header.Get("Content-Type"); got != "application/octet-stream" {
		t.Fatalf("Content-Type = %q", got)
	}
	if got := resp.Header.Get("Cache-Control"); got != "no-store" {
		t.Fatalf("Cache-Control = %q", got)
	}
	if got := resp.Header.Get("Server"); got != cfg.ServerHeader {
		t.Fatalf("Server = %q, want %q", got, cfg.ServerHeader)
	}
	body, err := io.ReadAll(resp.Body)
	resp.Body.Close()
	if err != nil {
		t.Fatalf("read tunnel response: %v", err)
	}
	if len(body) != 0 {
		t.Fatalf("tunnel response body = %q, want empty", body)
	}

	transport.CloseIdleConnections()
	_ = clientConn.Close()
	waitServe(t, serveErr, "ServeHTTP2")
}

